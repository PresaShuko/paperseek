from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys
import tempfile
from typing import Any

from paperseek_community.api import create_app
from paperseek_app.configuration import LLM_ROUTE_DEFAULTS, EMBEDDING_ROUTE_DEFAULTS, RERANKER_ROUTE_DEFAULTS, DECISION_ROUTE_DEFAULTS, DECISION_MODEL_OPTIONS


REPOSITORY = Path(__file__).resolve().parents[2]
OUTPUT = REPOSITORY / "web" / "src" / "api" / "generated.ts"
PRESETS_OUTPUT = REPOSITORY / "web" / "src" / "features" / "search" / "provider-presets.ts"


def _reference(value: str) -> str:
    return f'components["schemas"]["{value.rsplit("/", 1)[-1]}"]'


def _type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return _reference(str(schema["$ref"]))
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    if "enum" in schema:
        return " | ".join(json.dumps(value, ensure_ascii=False) for value in schema["enum"]) or "never"
    if "anyOf" in schema:
        return " | ".join(_type(item) for item in schema["anyOf"])
    if "oneOf" in schema:
        return " | ".join(_type(item) for item in schema["oneOf"])
    if "allOf" in schema:
        return " & ".join(_type(item) for item in schema["allOf"])
    kind = schema.get("type")
    if isinstance(kind, list):
        return " | ".join(_type({**schema, "type": item}) for item in kind)
    if kind == "array":
        return f"Array<{_type(schema.get('items', {}))}>"
    if kind == "object" or "properties" in schema:
        required = set(schema.get("required", []))
        members = [
            f"    {json.dumps(name)}{' ' if name in required else '?'}: {_type(value)};"
            for name, value in sorted(schema.get("properties", {}).items())
        ]
        additional = schema.get("additionalProperties")
        if additional is True:
            members.append("    [key: string]: unknown;")
        elif isinstance(additional, dict):
            members.append(f"    [key: string]: {_type(additional)};")
        return "{\n" + "\n".join(members) + "\n  }"
    if kind in {"integer", "number"}:
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "string":
        return "string"
    if kind == "null":
        return "null"
    return "unknown"


def render(schema: dict[str, Any] | None = None) -> str:
    if schema is None:
        with tempfile.TemporaryDirectory(prefix="paperseek-openapi-") as temporary:
            schema = create_app(Path(temporary) / "openapi.db").openapi()
    schemas = schema.get("components", {}).get("schemas", {})
    lines = [
        "// Generated by backend/scripts/generate_openapi_types.py. Do not edit.",
        "",
        "export interface components {",
        "  schemas: {",
    ]
    for name, definition in sorted(schemas.items()):
        rendered = _type(definition).replace("\n", "\n    ")
        lines.append(f"    {json.dumps(name)}: {rendered};")
    lines.extend(["  };", "}", ""])
    for name in sorted(schemas):
        lines.append(f'export type {name} = components["schemas"]["{name}"];')
    content = "\n".join(lines) + "\n"
    return "\n".join(line.rstrip() for line in content.splitlines()) + "\n"


def render_presets() -> str:
    tables = {
        "providerDefaults": {key: (model, api_type, base) for key, (api_type, base, model) in LLM_ROUTE_DEFAULTS.items()},
        "retrievalProviderDefaults": EMBEDDING_ROUTE_DEFAULTS,
        "rerankerProviderDefaults": RERANKER_ROUTE_DEFAULTS,
        "decisionProviderDefaults": DECISION_ROUTE_DEFAULTS,
        "decisionModelOptions": DECISION_MODEL_OPTIONS,
    }
    lines = ["// Generated from paperseek_app.configuration. Do not edit.", ""]
    for name, values in tables.items():
        lines.append(f"export const {name} = {{")
        lines.extend(f"  {json.dumps(key)}: {json.dumps(value, ensure_ascii=False)}," for key, value in values.items())
        lines.extend(["} as const;", ""])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for output, expected in ((OUTPUT, render()), (PRESETS_OUTPUT, render_presets())):
        if args.check:
            actual = output.read_text(encoding="utf-8") if output.is_file() else ""
            if actual != expected:
                print(f"Generated Web drift in {output.name}: run {Path(__file__).name} without --check", file=sys.stderr)
                return 1
        else:
            output.write_text(expected, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
