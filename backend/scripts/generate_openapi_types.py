from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys
import tempfile
from typing import Any

from paperseek_community.api import create_app


REPOSITORY = Path(__file__).resolve().parents[2]
OUTPUT = REPOSITORY / "web" / "src" / "api" / "generated.ts"


def _reference(value: str) -> str:
    return f'components["schemas"]["{value.rsplit("/", 1)[-1]}"]'


def _type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return _reference(str(schema["$ref"]))
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    if "enum" in schema:
        return " | ".join(json.dumps(value, ensure_ascii=False) for value in schema["enum"]) or "never"
    if "anyOf" in schema:
        return " | ".join(_type(item) for item in schema["anyOf"])
    if "oneOf" in schema:
        return " | ".join(_type(item) for item in schema["oneOf"])
    if "allOf" in schema:
        return " & ".join(_type(item) for item in schema["allOf"])
    kind = schema.get("type")
    if isinstance(kind, list):
        return " | ".join(_type({**schema, "type": item}) for item in kind)
    if kind == "array":
        return f"Array<{_type(schema.get('items', {}))}>"
    if kind == "object" or "properties" in schema:
        required = set(schema.get("required", []))
        members = [
            f"    {json.dumps(name)}{' ' if name in required else '?'}: {_type(value)};"
            for name, value in sorted(schema.get("properties", {}).items())
        ]
        additional = schema.get("additionalProperties")
        if additional is True:
            members.append("    [key: string]: unknown;")
        elif isinstance(additional, dict):
            members.append(f"    [key: string]: {_type(additional)};")
        return "{\n" + "\n".join(members) + "\n  }"
    if kind in {"integer", "number"}:
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "string":
        return "string"
    if kind == "null":
        return "null"
    return "unknown"


def render() -> str:
    with tempfile.TemporaryDirectory(prefix="paperseek-openapi-") as temporary:
        schema = create_app(Path(temporary) / "openapi.db").openapi()
    schemas = schema.get("components", {}).get("schemas", {})
    lines = [
        "// Generated by backend/scripts/generate_openapi_types.py. Do not edit.",
        "",
        "export interface components {",
        "  schemas: {",
    ]
    for name, definition in sorted(schemas.items()):
        rendered = _type(definition).replace("\n", "\n    ")
        lines.append(f"    {json.dumps(name)}: {rendered};")
    lines.extend(["  };", "}", ""])
    for name in sorted(schemas):
        lines.append(f'export type {name} = components["schemas"]["{name}"];')
    content = "\n".join(lines) + "\n"
    return "\n".join(line.rstrip() for line in content.splitlines()) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        actual = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else ""
        if actual != expected:
            print(f"OpenAPI TypeScript drift: run {Path(__file__).name} without --check", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(expected, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
