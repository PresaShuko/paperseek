from __future__ import annotations

from typing import Protocol

from paperseek_app.models import LeaseToken, PendingEvent, RunDetail
from paperseek_app.review.models import (
    OutlineSave, ReviewContent, ReviewDetail, ReviewJobContext, ReviewJobRequest,
    ReviewPage, ReviewRevision, SectionSave,
)


class ReviewStore(Protocol):
    def create_review(self, source_run_id: str, content: ReviewContent,
                      idempotency_key: str, request_digest: str) -> ReviewDetail: ...
    def get_review(self, review_id: str) -> ReviewDetail: ...
    def list_reviews(self, offset: int, limit: int, query: str = "") -> ReviewPage: ...
    def rename_review(self, review_id: str, title: str) -> None: ...
    def save_outline(self, review_id: str, request: OutlineSave) -> ReviewDetail: ...
    def save_section(self, review_id: str, section_id: str, request: SectionSave) -> ReviewDetail: ...
    def review_versions(self, review_id: str, part: str) -> list[ReviewRevision]: ...
    def submit_review_job(self, review_id: str, request: ReviewJobRequest, *, route: dict, credentials: dict,
                          idempotency_key: str, request_digest: str) -> RunDetail: ...
    def get_review_job(self, review_id: str, run_id: str) -> RunDetail: ...
    def review_job_context(self, run_id: str) -> ReviewJobContext: ...
    def persist_review_progress(self, lease: LeaseToken, review_id: str, expected_version: int,
                                content: ReviewContent, events: list[PendingEvent], *,
                                part: str = "", complete: bool = False) -> ReviewDetail: ...
    def delete_review(self, review_id: str, expected_version: int) -> None: ...
