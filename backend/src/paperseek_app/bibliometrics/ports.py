from typing import Protocol

from paperseek_app.bibliometrics.models import AnalysisPage, AnalysisRecord
from paperseek_app.models import StoredArtifact


class AnalysisStore(Protocol):
    def find_analysis(self, key: str) -> AnalysisRecord | None: ...
    def create_analysis(self, record: AnalysisRecord, key: str) -> AnalysisRecord: ...
    def get_analysis(self, identity: str) -> AnalysisRecord: ...
    def list_analyses(self, query: str, offset: int, limit: int) -> AnalysisPage: ...
    def rename_analysis(self, identity: str, title: str) -> None: ...
    def cache_network(
        self, identity: str, key: str, artifact: StoredArtifact
    ) -> StoredArtifact: ...
    def mark_analysis_deleted(self, identity: str) -> AnalysisRecord: ...
    def pending_analysis_deletions(self) -> list[AnalysisRecord]: ...
    def purge_analysis(self, identity: str) -> None: ...
